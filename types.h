/*****************************************************************************
 * @file      types.h
 * @brief     Independent Data Type Definitions for Embedded C Projects
 * @details   Standardized custom type abbreviations.
 *            Leading-underscore include guard removed (reserved in C89).
 *****************************************************************************/

#ifndef TYPES_H_
#define TYPES_H_

typedef const unsigned char  cu8;
typedef unsigned char        u8;
typedef signed char          s8;
typedef unsigned short int   u16;
typedef signed short int     s16;
typedef unsigned int         u32;
typedef signed int           s32;
typedef float                f32;

#endif /* TYPES_H_ */
